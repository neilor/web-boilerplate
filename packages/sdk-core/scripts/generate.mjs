// Generates TypeScript types from an explicit OpenAPI document and records where they came from.
//
//   node scripts/generate.mjs                       -> the synthetic contract in contracts/
//   OPENAPI_SOURCE=<file> OPENAPI_OUTPUT=<dir> ...  -> any other document (see docs/openapi-source.md)
//
// Output is deterministic: same input bytes + same generator version = same files.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { basename, dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(packageDir, '../..');

const source = resolve(process.env.OPENAPI_SOURCE ?? resolve(repoRoot, 'contracts/catalog.openapi.yaml'));
const outputDir = resolve(process.env.OPENAPI_OUTPUT ?? resolve(packageDir, 'src/generated'));
const outputName =
  process.env.OPENAPI_OUTPUT_NAME ?? basename(source).replace(/\.openapi\.(ya?ml|json)$|\.(ya?ml|json)$/, '');

// Hash the document with normalized line endings, so a Windows checkout produces the same hash.
const raw = (await readFile(source, 'utf8')).replace(/\r\n/g, '\n');
const sha256 = createHash('sha256').update(raw).digest('hex');

const ast = await openapiTS(pathToFileURL(source), { alphabetize: true });
const banner = [
  '// Generated by scripts/generate.mjs from an OpenAPI document. Do not edit by hand.',
  `// Source sha256: ${sha256}`,
  '',
].join('\n');
const types = banner + astToString(ast);

const require = createRequire(import.meta.url);
const generatorVersion = require('openapi-typescript/package.json').version;
const infoVersion = /^\s{2}version:\s*['"]?([^'"\n]+)['"]?\s*$/m.exec(raw)?.[1] ?? null;

// Only a repo-relative path is recorded. A document outside the repo is recorded by name only,
// so local directory names never end up in a committed file.
const relativeSource = relative(repoRoot, source).replaceAll('\\', '/');
const provenance = {
  source: relativeSource.startsWith('..') ? basename(source) : relativeSource,
  sha256,
  infoVersion,
  generator: `openapi-typescript@${generatorVersion}`,
  options: { alphabetize: true },
};

await mkdir(outputDir, { recursive: true });
await writeFile(resolve(outputDir, `${outputName}.ts`), types, 'utf8');
await writeFile(
  resolve(outputDir, `${outputName}.provenance.json`),
  `${JSON.stringify(provenance, null, 2)}\n`,
  'utf8',
);
console.log(`generated ${outputName}.ts from ${provenance.source} (sha256 ${sha256.slice(0, 12)})`);
